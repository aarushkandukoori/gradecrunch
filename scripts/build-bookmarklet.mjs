// Bundles bookmarklet/main.ts (plus the Canvas/Gradescope/Autolab sync code it imports) into one small
// minified script and writes it to src/generated/bookmarklet.ts, where the app reads it to build
// the draggable "Sync grades" link. Runs before every `npm run dev` / `npm run build`.
//
// The output is deterministic (no timestamps) and only rewritten when it changes, so rebuilding
// never creates a noisy git diff or a pointless dev-server reload.
//
// Usage: node scripts/build-bookmarklet.mjs           -> writes src/generated/bookmarklet.ts
//        node scripts/build-bookmarklet.mjs --stdout  -> prints the file instead (for checking)
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'src/generated/bookmarklet.ts')
const MAX_BYTES = 60 * 1024 // a javascript: link this big is already pushing what browsers accept

// Read the version number straight from the source so it is defined in exactly one place.
const versionSource = readFileSync(join(root, 'bookmarklet/version.ts'), 'utf8')
const versionMatch = versionSource.match(/BOOKMARKLET_VERSION\s*=\s*(\d+)/)
if (!versionMatch) throw new Error('Could not find BOOKMARKLET_VERSION in bookmarklet/version.ts')
const version = Number(versionMatch[1])

const result = await build({
  entryPoints: [join(root, 'bookmarklet/main.ts')],
  bundle: true,
  format: 'iife', // wraps everything in (() => {...})(), which evaluates to undefined, so the
  // browser stays on the page instead of replacing it with the script's return value
  minify: true,
  target: 'es2020',
  platform: 'browser',
  charset: 'utf8',
  legalComments: 'none',
  write: false,
  logLevel: 'silent',
})
const code = result.outputFiles[0].text.trim()

const bytes = Buffer.byteLength(code, 'utf8')
if (bytes > MAX_BYTES) {
  console.error(`Bookmarklet is ${bytes} bytes, over the ${MAX_BYTES} byte limit.`)
  process.exit(1)
}
const placeholders = code.split('__SITE_ORIGIN__').length - 1
if (placeholders !== 1) {
  console.error(`Expected the __SITE_ORIGIN__ placeholder once in the bundle, found it ${placeholders} times.`)
  process.exit(1)
}

const file =
  '// GENERATED by scripts/build-bookmarklet.mjs from bookmarklet/main.ts. Do not edit by hand:\n' +
  '// it is overwritten on every `npm run dev` / `npm run build`.\n' +
  `export const BOOKMARKLET_CODE: string = ${JSON.stringify(code)}\n` +
  `export const BOOKMARKLET_BUILT_VERSION: number = ${version}\n`

if (process.argv.includes('--stdout')) {
  process.stdout.write(file)
} else {
  let old = null
  try {
    old = readFileSync(outFile, 'utf8')
  } catch {
    // first build: no file yet
  }
  if (old !== file) {
    mkdirSync(dirname(outFile), { recursive: true })
    writeFileSync(outFile, file)
  }
  console.log(`Bookmarklet v${version}: ${(bytes / 1024).toFixed(1)} KB${old === file ? ' (unchanged)' : ''}`)
}
